public class RetroConsoleBlock extends BaseEntityBlock {

    public static final EnumProperty<Direction> FACING = BlockStateProperties.HORIZONTAL_FACING;
    public static final EnumProperty<ConsoleStyle> STYLE = EnumProperty.create("style", ConsoleStyle.class);
    public static final EnumProperty<ConsoleState> CONSOLE_STATE = EnumProperty.create("state", ConsoleState.class);
    public static final EnumProperty<RetroTone> TONE = EnumProperty.create("tone", RetroTone.class);
    public static final MapCodec<RetroConsoleBlock> CODEC = simpleCodec(RetroConsoleBlock::new);

    // One silhouette per style and visual state, generated by tools/derive-console-shapes.mjs.
    private static final Map<ConsoleStyle, Map<ConsoleState, Map<Direction, VoxelShape>>> SHAPES = createShapes();

    public RetroConsoleBlock(Properties properties) {
        super(properties);
        this.registerDefaultState(this.stateDefinition.any()
                .setValue(FACING, Direction.NORTH)
                .setValue(STYLE, ConsoleStyle.FULLBLOCK)
                .setValue(CONSOLE_STATE, ConsoleState.OFF)
                .setValue(TONE, RetroTone.CREAM));
    }

    private static Map<ConsoleStyle, Map<ConsoleState, Map<Direction, VoxelShape>>> createShapes() {
        Map<ConsoleStyle, Map<ConsoleState, Map<Direction, VoxelShape>>> shapes = new EnumMap<>(ConsoleStyle.class);
        for (ConsoleStyle style : ConsoleStyle.values()) {
            Map<ConsoleState, Map<Direction, VoxelShape>> states = new EnumMap<>(ConsoleState.class);
            for (ConsoleState state : ConsoleState.values()) {
                states.put(state, rotated(ConsoleShapes.boxes(style, state)));
            }
            shapes.put(style, states);
        }
        return shapes;
    }

    private static Map<Direction, VoxelShape> rotated(double[][] boxes) {
        VoxelShape shape = Shapes.empty();
        for (double[] box : boxes) {
            shape = Shapes.or(shape, Block.box(box[0], box[1], box[2], box[3], box[4], box[5]));
        }
        return Shapes.rotateHorizontal(shape);
    }

    @Override
    protected MapCodec<? extends BaseEntityBlock> codec() { return CODEC; }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING, STYLE, CONSOLE_STATE, TONE);
    }

    @Nullable
    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        return this.defaultBlockState().setValue(FACING, context.getHorizontalDirection().getOpposite());
    }

    @Override
    public RenderShape getRenderShape(BlockState state) {
        return RenderShape.MODEL;
    }

    @Override
    protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return SHAPES.get(state.getValue(STYLE)).get(state.getValue(CONSOLE_STATE)).get(state.getValue(FACING));
    }

    @Nullable
    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new RetroConsoleBlockEntity(pos, state);
    }

    @Nullable
    @Override
    public <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level level, BlockState state,
                                                                   BlockEntityType<T> type) {
        if (level.isClientSide()) return null;
        return (lvl, pos, st, be) -> {
            if (be instanceof RetroConsoleBlockEntity console) {
                RetroConsoleBlockEntity.serverTick(console);
                updateVisualState(console);
            }
        };
    }

    /** Mirrors the emulator runtime into the blockstate; the model set is picked from it. */
    static void updateVisualState(RetroConsoleBlockEntity console) {
        if (!(console.getLevel() instanceof ServerLevel level)) return;
        BlockState state = console.getBlockState();
        if (!state.hasProperty(CONSOLE_STATE)) return;
        ConsoleState visual = ConsoleState.of(console);
        if (state.getValue(CONSOLE_STATE) != visual) {
            level.setBlock(console.getBlockPos(), state.setValue(CONSOLE_STATE, visual), Block.UPDATE_CLIENTS);
        }
    }

    @Override
    protected InteractionResult useItemOn(ItemStack stack, BlockState state, Level level,
                                          BlockPos pos, Player player, InteractionHand hand,
                                          BlockHitResult hitResult) {
        // A chassis dye repaints the finish; the tone never changes the shape.
        RetroTone painted = RetroTone.ofDye(stack.get(DataComponents.DYE));
        if (painted != null) {
            if (!level.isClientSide() && state.getValue(TONE) != painted) {
                level.setBlock(pos, state.setValue(TONE, painted), Block.UPDATE_ALL);
                player.sendOverlayMessage(Component.translatable("retroconsole.tone.painted",
                        Component.translatable(painted.translationKey())));
            }
            return InteractionResult.SUCCESS;
        }
        if (!player.getItemInHand(hand).isEmpty()) {
            return InteractionResult.PASS;
        }
        if (player.isShiftKeyDown()) {
            // Sneak-use cycles the cosmetic chassis without opening the screen.
            if (!level.isClientSide()) {
                level.setBlock(pos, state.setValue(STYLE, state.getValue(STYLE).next()), Block.UPDATE_ALL);
            }
            return InteractionResult.SUCCESS;
        }
        if (level.isClientSide()) {
            return InteractionResult.SUCCESS;
        }
        if (!(level.getBlockEntity(pos) instanceof RetroConsoleBlockEntity console)
                || !(player instanceof ServerPlayer serverPlayer)) {
            return InteractionResult.PASS;
        }

        String romId = console.getRomId();
        if (!romId.isEmpty() && console.getConsoleId() != null
                && !ServerConsoles.hasEmulator(console.getConsoleId())
                // A boot in flight has no Entry yet — do not restart it on every click.
                && !ServerConsoles.isBooting(console.getConsoleId())) {
            if (!console.getCoreName().isEmpty()) {
                UUID owner = console.getOwnerId() != null ? console.getOwnerId() : serverPlayer.getUUID();
                console.selectGame(console.getCoreName(), romId, owner, true);
            } else {
                console.powerOff();
            }
        }

        NetAccess.sendToPlayer(serverPlayer, RetroPayloads.OPEN_SCREEN,
                new RetroOpenScreenPacket(
                        pos, console.getOrAssignConsoleId(), console.getRomId(),
                        RomLibrary.systemIdForRomPath(console.getRomId())));
        return InteractionResult.SUCCESS;
    }

    @Override
    public void onPlace(BlockState state, Level level, BlockPos pos, BlockState oldState, boolean movedByPiston) {
        super.onPlace(state, level, pos, oldState, movedByPiston);
        if (!level.isClientSide() && !oldState.is(this)) {
            ScreenMultiblocks.onConsoleChanged(level, pos);
        }
    }

    @Override
    protected void affectNeighborsAfterRemoval(BlockState state, ServerLevel level, BlockPos pos,
                                               boolean movedByPiston) {
        super.affectNeighborsAfterRemoval(state, level, pos, movedByPiston);
        ScreenMultiblocks.onConsoleChanged(level, pos);
    }

    @Override
    protected boolean propagatesSkylightDown(BlockState state) {
        return true;
    }
}
