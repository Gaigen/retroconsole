// Derives per-style collision boxes from the ported console models:
//   node tools/derive-console-shapes.mjs
// Each column of the model contributes its full vertical extent, so recesses and
// cartridges never leave pockets a player could clip into. Shapes are derived per
// visual state: the cartridge is only solid on the model that draws it.
// Output: ConsoleShapes.java (generated, committed).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const resolution = 32; // columns per block edge
const styles = ['classic', 'compact', 'hifi', 'legacy', 'fullblock'];
const states = ['off', 'standby', 'running'];
const models = new URL('../common/src/main/resources/assets/retroconsole/models/block/console/', import.meta.url);
const out = new URL('../common/src/main/java/com/retroconsole/block/ConsoleShapes.java', import.meta.url);
const unit = 16 / resolution;

// Heights are snapped outwards to half units so neighbouring columns merge.
const snapLow = value => Math.max(0, Math.floor(value * 2) / 2);
const snapHigh = value => Math.min(16, Math.ceil(value * 2) / 2);

const columns = elements => {
  const low = new Float64Array(resolution * resolution).fill(Infinity);
  const high = new Float64Array(resolution * resolution).fill(-Infinity);
  for (const { from, to } of elements) {
    const x0 = Math.max(0, Math.floor(from[0] / unit));
    const x1 = Math.min(resolution, Math.ceil(to[0] / unit));
    const z0 = Math.max(0, Math.floor(from[2] / unit));
    const z1 = Math.min(resolution, Math.ceil(to[2] / unit));
    for (let z = z0; z < z1; z++) {
      for (let x = x0; x < x1; x++) {
        const index = z * resolution + x;
        low[index] = Math.min(low[index], snapLow(from[1]));
        high[index] = Math.max(high[index], snapHigh(to[1]));
      }
    }
  }
  return { low, high };
};

// Sweep the columns into boxes, merging along x first and then along z.
const boxes = ({ low, high }) => {
  const used = new Uint8Array(resolution * resolution);
  const result = [];
  for (let z = 0; z < resolution; z++) {
    for (let x = 0; x < resolution; x++) {
      const index = z * resolution + x;
      if (used[index] || !Number.isFinite(low[index])) continue;
      let x1 = x;
      while (x1 + 1 < resolution) {
        const next = z * resolution + x1 + 1;
        if (used[next] || low[next] !== low[index] || high[next] !== high[index]) break;
        x1++;
      }
      let z1 = z;
      grow: while (z1 + 1 < resolution) {
        for (let i = x; i <= x1; i++) {
          const next = (z1 + 1) * resolution + i;
          if (used[next] || low[next] !== low[index] || high[next] !== high[index]) break grow;
        }
        z1++;
      }
      for (let j = z; j <= z1; j++) {
        for (let i = x; i <= x1; i++) used[j * resolution + i] = 1;
      }
      result.push([x * unit, low[index], z * unit, (x1 + 1) * unit, high[index], (z1 + 1) * unit]);
    }
  }
  return result;
};

const number = value => Number(value.toFixed(5)).toString();
const lines = [
  'package com.retroconsole.block;',
  '',
  '/**',
  ' * Collision/selection boxes per console style and visual state, derived from the',
  ' * block models, so the cartridge is only solid while it is drawn.',
  ' * <p>',
  ' * Generated by {@code tools/derive-console-shapes.mjs} from',
  ' * {@code assets/retroconsole/models/block/console}. Do not edit by hand.',
  ' */',
  'public final class ConsoleShapes {',
  '',
];
const emitted = new Map();
const table = [];
for (const style of styles) {
  table.push(states.map(state => {
    const elements = JSON.parse(readFileSync(new URL(`${style}/${state}.json`, models), 'utf8')).elements;
    const solid = elements.every(({ to }) => to[1] <= 16)
      && elements.some(({ from }) => from.every((value, axis) => value === 0))
      && elements.some(({ to }) => to.every(value => value === 16));
    const shape = solid ? [[0, 0, 0, 16, 16, 16]] : boxes(columns(elements));
    const top = Math.max(...shape.map(box => box[4])).toFixed(3);
    console.log(`${style}/${state}: ${shape.length} boxes, top ${top}`);
    const key = JSON.stringify(shape);
    if (emitted.has(key)) return emitted.get(key);
    const name = `${style.toUpperCase()}_${state.toUpperCase()}`;
    emitted.set(key, name);
    lines.push(`    static final double[][] ${name} = {`);
    for (const box of shape) lines.push(`            {${box.map(number).join(', ')}},`);
    lines.push('    };', '');
    return name;
  }));
}
lines.push(
  '    /** Boxes for {@code style} in {@code state}: {@code {x1, y1, z1, x2, y2, z2}} in model units. */',
  '    public static double[][] boxes(ConsoleStyle style, ConsoleState state) {',
  '        return switch (style) {',
);
table.forEach((row, index) => {
  lines.push(`            case ${styles[index].toUpperCase()} -> switch (state) {`);
  row.forEach((name, state) => lines.push(`                case ${states[state].toUpperCase()} -> ${name};`));
  lines.push('            };');
});
lines.push(
  '        };',
  '    }',
  '',
  '    private ConsoleShapes() {}',
  '}',
  '',
);
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${fileURLToPath(out)}`);
